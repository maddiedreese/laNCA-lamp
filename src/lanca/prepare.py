"""Phase 2 pipeline: footage -> stabilized crops -> wax masks -> QA previews -> behavior stats.

    uv run python -m lanca.prepare lamp-2026-10-25            # all stages
    uv run python -m lanca.prepare lamp-2026-10-25 masks qa   # re-run later stages only

Stages and outputs:
    crops  runs/cache/<id>/crops.npy   stabilized glass crops at 2x grid size (gitignored, large)
    masks  masks/<id>.npz (10 fps, local only), masks/<id>_2fps.npz (committed), masks/<id>.json
           soft wax masks on the grid, vessel, settings
    qa     runs/qa/<id>/   side-by-side preview video and contact sheets
    stats  stats/<id>.json   behavior targets; per-frame series in runs/qa/<id>/series.npz
"""

import argparse
import json
import time
from pathlib import Path

import cv2
import numpy as np

from lanca import measure, segment
from lanca.extract import ROOT, ClipConfig, stabilized_crops

FPS = 10.0
CROP_SCALE = 2  # cached crops are this many times the grid size


def cache_dir(clip_id: str) -> Path:
    return ROOT / "runs" / "cache" / clip_id


def stage_crops(cfg: ClipConfig) -> None:
    out = cache_dir(cfg.id)
    out.mkdir(parents=True, exist_ok=True)
    manifest = json.loads((ROOT / "footage" / "manifest.json").read_text())
    duration = next(c for c in manifest["clips"] if c["id"] == cfg.id)["duration_s"]
    gh, gw = cfg.grid
    size = (gw * CROP_SCALE, gh * CROP_SCALE)
    n_max = int(duration * FPS) + 2
    crops = np.lib.format.open_memmap(
        out / "crops.tmp.npy", "w+", np.uint8, (n_max, size[1], size[0], 3)
    )
    times = np.zeros(n_max, np.float32)
    transforms = np.zeros((n_max, 2, 3), np.float32)
    scores = np.zeros((n_max, 2), np.float32)
    start = time.time()
    n = 0
    for t, crop, m, s in stabilized_crops(cfg, FPS):
        crops[n] = cv2.resize(crop, size, interpolation=cv2.INTER_AREA)
        times[n], transforms[n], scores[n] = t, m, list(s.values())
        n += 1
        if n % 6000 == 0:
            print(
                f"  crops: {n / FPS / 60:.0f} min of footage, {time.time() - start:.0f}s elapsed",
                flush=True,
            )
    crops.flush()
    del crops
    # Trim to the frames actually decoded.
    full = np.load(out / "crops.tmp.npy", mmap_mode="r")
    final = np.lib.format.open_memmap(out / "crops.npy", "w+", np.uint8, (n, *full.shape[1:]))
    for i in range(0, n, 2000):
        final[i : i + 2000] = full[i : min(n, i + 2000)]
    final.flush()
    del final, full
    (out / "crops.tmp.npy").unlink()
    np.savez(
        out / "crops_meta.npz", t=times[:n], transforms=transforms[:n], anchor_scores=scores[:n]
    )
    print(
        f"  crops: {n} frames in {time.time() - start:.0f}s; min anchor score {scores[:n].min():.3f}"
    )


def stage_masks(cfg: ClipConfig) -> None:
    src = cache_dir(cfg.id)
    crops = np.load(src / "crops.npy", mmap_mode="r")
    meta = np.load(src / "crops_meta.npz")
    sample = np.asarray(crops[:: max(1, len(crops) // 600)])
    vessel = segment.vessel_mask(sample)
    model = segment.WaxModel.fit(sample, vessel)
    gvessel = segment.grid_vessel(vessel, cfg.grid)

    start = time.time()
    masks = np.zeros((len(crops), *cfg.grid), np.uint8)
    for i in range(len(crops)):
        masks[i] = np.round(segment.to_grid(model(crops[i]), vessel, cfg.grid) * gvessel * 255)
        if (i + 1) % 12000 == 0:
            print(f"  masks: {i + 1}/{len(crops)}, {time.time() - start:.0f}s", flush=True)

    out = ROOT / "masks"
    # The full-rate file is too big for git (GitHub caps files at 100 MB), so it stays local and
    # a 2 fps copy is committed. Both are regenerated by this stage.
    np.savez_compressed(out / f"{cfg.id}.npz", masks=masks, t=meta["t"], vessel=gvessel, fps=FPS)
    step = int(FPS / 2)
    np.savez_compressed(
        out / f"{cfg.id}_2fps.npz",
        masks=masks[::step],
        t=meta["t"][::step],
        vessel=gvessel,
        fps=FPS / step,
    )
    np.savez_compressed(
        src / "segmentation.npz", vessel=vessel, glare=model.glare, threshold=model.threshold
    )
    info = {
        "clip": cfg.id,
        "fps": FPS,
        "frames": len(masks),
        "grid": list(cfg.grid),
        "encoding": "uint8 wax probability, 0-255; cells outside the vessel are 0",
        "glass_box": list(cfg.glass_box),
        "anchors": {k: list(v) for k, v in cfg.anchors.items()},
        "min_anchor_score": float(meta["anchor_scores"].min()),
        "vessel_cells": int(gvessel.sum()),
        "wax_model": {
            **model.params,
            "softness": model.softness,
            "hot_l": model.hot_l,
            "hot_softness": model.hot_softness,
        },
    }
    (out / f"{cfg.id}.json").write_text(json.dumps(info, indent=2) + "\n")
    size_mb = (out / f"{cfg.id}.npz").stat().st_size / 1e6
    print(f"  masks: {len(masks)} frames, {size_mb:.1f} MB, {time.time() - start:.0f}s")


def stage_qa(cfg: ClipConfig) -> None:
    crops = np.load(cache_dir(cfg.id) / "crops.npy", mmap_mode="r")
    data = np.load(ROOT / "masks" / f"{cfg.id}.npz")
    masks, t = data["masks"], data["t"]
    out = ROOT / "runs" / "qa" / cfg.id
    out.mkdir(parents=True, exist_ok=True)
    h, w = crops.shape[1:3]

    def panel(i: int) -> np.ndarray:
        rgb = np.asarray(crops[i])
        m = cv2.resize(masks[i], (w, h), interpolation=cv2.INTER_NEAREST)
        overlay = rgb.copy()
        edge = cv2.Canny((m >= 128).astype(np.uint8) * 255, 50, 150) > 0
        overlay[edge] = (0, 255, 0)
        mask_rgb = np.repeat(m[..., None], 3, 2)
        p = np.concatenate([rgb, overlay, mask_rgb], 1)
        cv2.putText(
            p, f"{t[i] / 60:5.1f} min", (4, 16), cv2.FONT_HERSHEY_SIMPLEX, 0.45, (255, 255, 255), 1
        )
        return p

    # Full recording at 2 fps sampled frames, played at 60 fps: 2 hours in about 4 minutes.
    step = int(FPS / 2)
    first = panel(0)
    writer = cv2.VideoWriter(
        str(out / "preview_30x.mp4"), cv2.VideoWriter_fourcc(*"mp4v"), 60, first.shape[1::-1]
    )
    for i in range(0, len(masks), step):
        writer.write(cv2.cvtColor(panel(i), cv2.COLOR_RGB2BGR))
    writer.release()

    # Real-time 60 s excerpt from steady cycling, for checking blob motion frame to frame.
    s = min(len(masks) - 1, int(5400 * FPS))
    writer = cv2.VideoWriter(
        str(out / "excerpt_realtime.mp4"), cv2.VideoWriter_fourcc(*"mp4v"), FPS, first.shape[1::-1]
    )
    for i in range(s, min(len(masks), s + int(60 * FPS))):
        writer.write(cv2.cvtColor(panel(i), cv2.COLOR_RGB2BGR))
    writer.release()

    idx = np.linspace(0, len(masks) - 1, 16).astype(int)
    sheet = np.concatenate(
        [np.concatenate([panel(i) for i in idx[r * 4 : r * 4 + 4]], 1) for r in range(4)], 0
    )
    cv2.imwrite(str(out / "sheet.jpg"), cv2.cvtColor(sheet, cv2.COLOR_RGB2BGR))
    print(f"  qa: wrote {out.relative_to(ROOT)}")


def stage_stats(cfg: ClipConfig) -> None:
    data = np.load(ROOT / "masks" / f"{cfg.id}.npz")
    masks = data["masks"].astype(np.float32) / 255
    fps = float(data["fps"])
    stats, series = measure.summarize(masks, data["vessel"], fps)
    stats = {"clip": cfg.id, "units": "lengths in lamp heights, times in seconds", **stats}
    (ROOT / "stats" / f"{cfg.id}.json").write_text(json.dumps(stats, indent=2) + "\n")
    out = ROOT / "runs" / "qa" / cfg.id
    out.mkdir(parents=True, exist_ok=True)
    np.savez_compressed(out / "series.npz", t=data["t"], **series)
    print("  stats:", json.dumps(stats["phases"]))


STAGES = {"crops": stage_crops, "masks": stage_masks, "qa": stage_qa, "stats": stage_stats}


def main() -> None:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("clip")
    ap.add_argument("stages", nargs="*", help=f"any of: {', '.join(STAGES)} (default: all)")
    args = ap.parse_args()
    unknown = set(args.stages) - set(STAGES)
    if unknown:
        ap.error(f"unknown stage(s): {', '.join(sorted(unknown))}")
    cfg = ClipConfig.load(args.clip)
    for name in args.stages or STAGES:
        print(f"[{name}]", flush=True)
        STAGES[name](cfg)


if __name__ == "__main__":
    main()
